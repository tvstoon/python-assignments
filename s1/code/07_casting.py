# تبدیل به عدد صحیح
number = int("10")
print(number)

# تبدیل به عدد اعشاری
price = float("12.5")
print(price)

# تبدیل به متن
age = str(25)
print(age)

x = "20"

print(int(x))    # 20
print(float(x))  # 20.0
print(str(x))    # "20"

# تبدیل به Boolean
print(bool(1))       # True
print(bool(0))       # False

print(bool("Hello"))  # True
print(bool(""))      # False
